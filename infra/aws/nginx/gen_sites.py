#!/usr/bin/env python3
"""Generate the nb-nginx-sites bundle (sites/*.conf) from vm-agent/services.json.

Source of truth for routing = the prod HA VM nginx (api/dashboard/sso/cdn/sign/portal/
partner/mcp/apex/neonbee-store), re-rooted for AWS nodes: static frontends are served
from /opt/neonbee/services/<svc>/current/dist, backends/Next apps from 127.0.0.1:<port>.
Only catalog apps are emitted (no Dev, Command, website or client sites). tools.neonbee.app
(Free Tools = shell-fe-tools) is platform and served here since phase 3 (2026-11-22).

    python3 gen_sites.py [--out DIR]      # default: ./sites next to this file
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.join(HERE, "..", "vm-agent", "services.json")
SERVICES_ROOT = "/opt/neonbee/services"
CF_CERT = ("/etc/ssl/cloudflare/neonbee.app.crt", "/etc/ssl/cloudflare/neonbee.app.key")
STORE_CERT = ("/etc/ssl/certs/neonbee-store.crt", "/etc/ssl/private/neonbee-store.key")
CDN_PREFIX_RE = re.compile(r"^/var/www/cdn\.neonbee\.app/html/([a-z0-9-]+)$")

# api.neonbee.app gateway: /<module>/ -> catalog backend (prod order). mobility is not
# in the catalog (unused), so it is not routed. ws=True keeps the Upgrade headers prod uses.
GATEWAY = [
    ("core", "core-prod", False), ("crm", "crm-prod", False), ("marketing", "marketing-prod", False),
    ("signal", "signal-prod", False), ("inventory", "inventory-prod", False),
    ("accounting", "accounting-prod", False), ("projects", "projects-prod", False),
    ("timesheet", "timesheet-prod", False), ("people", "people-connect-prod", False),
    ("inbox", "inbox-prod", True), ("neura", "neura-prod", False),
    ("storefront", "storefront-api-prod", False), ("flow", "flow-prod", False),
    ("insight", "insight-prod", False), ("subscription", "subscription-prod", False),
    ("forms", "forms-prod", False), ("dailystore", "dailystore-admin-prod", False),
    ("fulfillment", "fulfillment-prod", False), ("support", "support-prod", True),
    ("manufacturing", "manufacturing-prod", False), ("chat", "chat-prod", True),
    ("documents", "documents-prod", False), ("sign", "sign-prod", False),
    ("folio", "folio-prod", False),
]

CF_RANGES = """173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18
108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17
162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22
2400:cb00::/32 2606:4700::/32 2803:f800::/32 2405:b500::/32 2405:8100::/32
2a06:98c0::/29 2c0f:f248::/32""".split()

HEADER = "# GENERATED by infra/aws/nginx/gen_sites.py from vm-agent/services.json - do not edit by hand.\n"
LB = "    include /etc/nginx/snippets/nb-lb-health.conf;\n"
PROXY_HDRS = (
    "        proxy_set_header Host $host;\n"
    "        proxy_set_header X-Real-IP $remote_addr;\n"
    "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
    "        proxy_set_header X-Forwarded-Proto $scheme;\n"
    "        proxy_read_timeout 300s;\n"
)
ASSET_EXT = r"js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot"
CORS = ('    add_header Access-Control-Allow-Origin "*" always;\n'
        '    add_header Access-Control-Allow-Methods "GET, OPTIONS" always;\n'
        '    add_header Access-Control-Allow-Headers "Origin, Content-Type, Accept" always;\n')


def load_catalog(path=CATALOG):
    with open(path) as f:
        return {s["name"]: s for s in json.load(f)["services"]}


def dist(svc):
    return "%s/%s/current/dist" % (SERVICES_ROOT, svc)


def redirect80(host, extra_names=""):
    return ("server {\n    listen 80; listen [::]:80;\n    server_name %s%s;\n%s"
            "    location / { return 301 https://$host$request_uri; }\n}\n" % (host, extra_names, LB))


def tls_server_head(host, cert, logname=None, extra_names=""):
    logname = logname or host
    return ("server {\n    listen 443 ssl http2; listen [::]:443 ssl http2;\n    server_name %s%s;\n"
            "    ssl_certificate %s;\n    ssl_certificate_key %s;\n"
            "    ssl_protocols TLSv1.2 TLSv1.3;\n    ssl_ciphers HIGH:!aNULL:!MD5;\n"
            "    access_log /var/log/nginx/%s-access.log;\n    error_log /var/log/nginx/%s-error.log;\n%s"
            % (host, extra_names, cert[0], cert[1], logname, logname, LB))


def http_conf(cat):
    out = [HEADER, "# http-context: Cloudflare real client IP + api gateway upstreams.\n"]
    out += ["set_real_ip_from %s;\n" % r for r in CF_RANGES]
    out.append("real_ip_header CF-Connecting-IP;\n\n")
    for mod, svc, _ in GATEWAY:
        if svc in cat:
            out.append("upstream nb_%s { server 127.0.0.1:%d; keepalive 32; }\n" % (svc.replace("-", "_"), cat[svc]["port"]))
    return "".join(out)


def api_conf(cat):
    out = [HEADER, redirect80("api.neonbee.app"), tls_server_head("api.neonbee.app", CF_CERT),
           "    client_max_body_size 50M;\n\n",
           "    location = / {\n        return 200 '{\"service\":\"NeonBee API Gateway\",\"version\":\"2.0\",\"environment\":\"aws\"}';\n"
           "        add_header Content-Type application/json;\n    }\n\n",
           "    location = /health {\n        return 200 '{\"status\":\"ok\",\"environment\":\"aws\"}';\n"
           "        add_header Content-Type application/json;\n    }\n\n"]
    for mod, svc, ws in GATEWAY:
        if svc not in cat:
            continue
        conn = ('proxy_set_header Upgrade $http_upgrade; proxy_set_header Connection "upgrade";' if ws
                else 'proxy_set_header Connection "";')
        out.append("    location /%s/ {\n        rewrite ^/%s/(.*) /$1 break;\n        proxy_pass http://nb_%s;\n%s"
                   "        proxy_http_version 1.1;\n        %s\n    }\n"
                   % (mod, mod, svc.replace("-", "_"), PROXY_HDRS, conn))
    out.append("}\n")
    return "".join(out)


def spa_conf(host, svc, extra_names=""):
    """Whole-host static SPA (dashboard, sso): root = dist, SPA fallback, remoteEntry no-cache."""
    return "".join([HEADER, redirect80(host, extra_names), tls_server_head(host, CF_CERT, extra_names=extra_names),
        "    root %s;\n    index index.html;\n\n" % dist(svc),
        "    location / {\n        try_files $uri $uri/ /index.html;\n    }\n\n",
        '    # remoteEntry.js - never cache (Module Federation host must always get the latest)\n'
        '    location ~* /assets/remoteEntry\\.js$ {\n        add_header Cache-Control "no-cache, no-store, must-revalidate" always;\n    }\n\n',
        "    location ~* \\.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot|mjs)$ {\n"
        '        expires 1y;\n        add_header Cache-Control "public, immutable" always;\n    }\n}\n'])


def cdn_prefixes(cat):
    """(prefix, svc) for every static catalog app that prod serves under cdn.neonbee.app/<prefix>/."""
    res = []
    for name, s in cat.items():
        m = CDN_PREFIX_RE.match(s.get("prod_nginx_root", ""))
        if s.get("static") and m:
            res.append((m.group(1), name))
    return sorted(res)


def cdn_conf(cat):
    pref = cdn_prefixes(cat)
    out = [HEADER, redirect80("cdn.neonbee.app"), tls_server_head("cdn.neonbee.app", CF_CERT), CORS, "\n"]
    out.append("    # remoteEntry.js - never cache (listed first: regex locations match in order)\n")
    for p, svc in pref:
        out.append('    location ~* ^/%s/assets/remoteEntry\\.js$ {\n        alias %s/assets/remoteEntry.js;\n'
                   '        add_header Cache-Control "no-cache, no-store, must-revalidate" always;\n'
                   '        add_header Access-Control-Allow-Origin "*" always;\n    }\n' % (p, dist(svc)))
    out.append("\n    # .mjs workers need a JS MIME type\n")
    for p, svc in pref:
        out.append('    location ~* ^/%s/(.+\\.mjs)$ {\n        alias %s/$1;\n        default_type application/javascript;\n'
                   '        expires 1y;\n        add_header Cache-Control "public, immutable" always;\n'
                   '        add_header Access-Control-Allow-Origin "*" always;\n    }\n' % (p, dist(svc)))
    out.append("\n    # hashed static assets - long cache, immutable\n")
    for p, svc in pref:
        out.append('    location ~* ^/%s/(.+\\.(?:%s))$ {\n        alias %s/$1;\n        expires 1y;\n'
                   '        add_header Cache-Control "public, immutable" always;\n'
                   '        add_header Access-Control-Allow-Origin "*" always;\n    }\n' % (p, ASSET_EXT, dist(svc)))
    out.append("\n")
    for p, svc in pref:
        out.append("    location /%s/ {\n        alias %s/;\n        try_files $uri $uri/ /%s/index.html;\n    }\n" % (p, dist(svc), p))
    out.append("\n    location / {\n        return 404;\n    }\n}\n")
    return "".join(out)


def sign_conf(cat):
    d = dist("sign-public-fe")
    return "".join([HEADER, redirect80("sign.neonbee.app"), tls_server_head("sign.neonbee.app", CF_CERT),
        "    gzip on; gzip_types text/plain text/css application/json application/javascript text/xml;\n\n",
        "    location ~* ^/s/(.+\\.(?:%s|map))$ {\n        alias %s/$1;\n        expires 1y;\n"
        "        add_header Cache-Control 'public, immutable' always;\n    }\n\n" % (ASSET_EXT, d),
        "    location /s/ {\n        alias %s/;\n        add_header Cache-Control 'no-cache, must-revalidate' always;\n"
        "        try_files $uri $uri/ /s/index.html;\n    }\n\n" % d,
        "    location = / { return 302 https://sign.neonbee.app/s/; }\n}\n"])


def portal_conf(cat):
    return "".join([HEADER, redirect80("portal.neonbee.app"), tls_server_head("portal.neonbee.app", CF_CERT),
        "    root %s;\n    index index.html;\n\n" % dist("client-portal-pwa"),
        "    gzip on;\n    gzip_types text/plain text/css application/json application/javascript text/xml application/manifest+json;\n\n",
        "    location ~* \\.(js|css|png|svg|ico|woff2|webmanifest)$ {\n        expires 1y;\n"
        '        add_header Cache-Control "public, immutable" always;\n        try_files $uri =404;\n    }\n\n',
        '    location / {\n        add_header Cache-Control "no-cache, must-revalidate" always;\n'
        "        try_files $uri $uri/ /index.html;\n    }\n}\n"])


def partner_conf(cat):
    port = cat["partner-portal-prod"]["port"]
    return "".join([HEADER, redirect80("partner.neonbee.app"), tls_server_head("partner.neonbee.app", CF_CERT),
        "    proxy_set_header Host $host;\n    proxy_set_header X-Real-IP $remote_addr;\n"
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n    proxy_set_header X-Forwarded-Proto https;\n"
        "    proxy_set_header X-Forwarded-Host $host;\n    proxy_http_version 1.1;\n    proxy_set_header Connection \"\";\n\n",
        "    location /_next/static/ {\n        proxy_pass http://127.0.0.1:%d;\n        expires 1y;\n"
        '        add_header Cache-Control "public, immutable" always;\n    }\n\n' % port,
        "    location /api/health {\n        proxy_pass http://127.0.0.1:%d;\n        access_log off;\n    }\n\n" % port,
        "    location / {\n        proxy_pass http://127.0.0.1:%d;\n        proxy_buffering off;\n    }\n}\n" % port])


def mcp_conf(cat):
    up = "nb_neura_prod"
    return "".join([HEADER, redirect80("mcp.neonbee.app"), tls_server_head("mcp.neonbee.app", CF_CERT),
        "    client_max_body_size 10M;\n    location / {\n        proxy_pass http://%s;\n%s"
        '        proxy_http_version 1.1;\n        proxy_set_header Connection "";\n        proxy_buffering off;\n'
        "        proxy_cache off;\n    }\n}\n" % (up, PROXY_HDRS)])


def apex_conf(cat):
    return "".join([HEADER, redirect80("neonbee.app", " www.neonbee.app"),
        tls_server_head("neonbee.app", CF_CERT, extra_names=" www.neonbee.app"),
        "    # Public forms SPA (/forms/public/<token>, /forms/embed, ...)\n",
        "    location /forms/ {\n        alias %s/;\n        add_header Cache-Control \"no-cache, must-revalidate\" always;\n"
        "        try_files $uri $uri/ /forms/index.html;\n    }\n\n" % dist("forms-fe"),
        "    # everything else -> SSO login\n    location / {\n        return 301 https://sso.neonbee.app$request_uri;\n    }\n}\n"])


# Apex (wildcard does not match it) + the CF-for-SaaS fallback origin, named explicitly so the
# cf-cutover allow-list (server_name scan) can switch them. Phase 3, 2026-11-22.
STORE_EXTRA = " neonbee.store customers-fallback.neonbee.store"


def store_conf(cat):
    web, api = cat["storefront-web-prod"]["port"], cat["storefront-api-prod"]["port"]
    return "".join([HEADER,
        "server {\n    listen 80; listen [::]:80;\n    server_name *.neonbee.store%s;\n%s"
        "    location / { return 301 https://$host$request_uri; }\n}\n" % (STORE_EXTRA, LB),
        tls_server_head("*.neonbee.store", STORE_CERT, logname="neonbee-store", extra_names=STORE_EXTRA),
        "    location /nginx-health {\n        return 200 'ok';\n        add_header Content-Type text/plain;\n    }\n\n"
        "    # Same-origin API: https://<store>.neonbee.store/v1/storefront/... -> storefront API\n"
        "    location /v1/ {\n        proxy_pass http://127.0.0.1:%d;\n        proxy_http_version 1.1;\n"
        "        proxy_set_header Host $host;\n        proxy_set_header X-Real-IP $remote_addr;\n"
        "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n        proxy_set_header X-Forwarded-Proto https;\n"
        "        proxy_read_timeout 60s;\n    }\n\n" % api,
        "    location / {\n        proxy_pass http://127.0.0.1:%d;\n        proxy_http_version 1.1;\n"
        "        proxy_set_header Host $host;\n        proxy_set_header X-Real-IP $remote_addr;\n"
        "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n        proxy_set_header X-Forwarded-Proto https;\n"
        "        proxy_set_header Upgrade $http_upgrade;\n        proxy_set_header Connection 'upgrade';\n"
        "        proxy_cache_bypass $http_upgrade;\n        proxy_read_timeout 60s;\n    }\n}\n" % web])


def tools_conf(cat):
    """tools.neonbee.app = shell-fe-tools (shell, tools flavor). Mirrors the HA vhost: SPA, index no-cache."""
    return "".join([HEADER, redirect80("tools.neonbee.app"), tls_server_head("tools.neonbee.app", CF_CERT),
        "    root %s;\n    index index.html;\n\n" % dist("shell-fe-tools"),
        "    location = /index.html {\n"
        '        add_header Cache-Control "no-cache, no-store, must-revalidate" always;\n        expires 0;\n    }\n\n',
        "    location / {\n        try_files $uri $uri/ /index.html;\n    }\n\n",
        "    location ~* \\.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot|mjs)$ {\n"
        '        expires 1y;\n        add_header Cache-Control "public, immutable" always;\n    }\n}\n'])


def render_all(cat):
    return {
        "00-nb-http.conf": http_conf(cat),
        "api.neonbee.app.conf": api_conf(cat),
        "dashboard.neonbee.app.conf": spa_conf("dashboard.neonbee.app", "shell-fe"),
        "sso.neonbee.app.conf": spa_conf("sso.neonbee.app", "sso-fe"),
        "cdn.neonbee.app.conf": cdn_conf(cat),
        "sign.neonbee.app.conf": sign_conf(cat),
        "portal.neonbee.app.conf": portal_conf(cat),
        "partner.neonbee.app.conf": partner_conf(cat),
        "mcp.neonbee.app.conf": mcp_conf(cat),
        "neonbee.app.conf": apex_conf(cat),
        "neonbee-store.conf": store_conf(cat),
        "tools.neonbee.app.conf": tools_conf(cat),
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "sites"))
    ap.add_argument("--catalog", default=CATALOG)
    a = ap.parse_args(argv)
    files = render_all(load_catalog(a.catalog))
    os.makedirs(a.out, exist_ok=True)
    for old in os.listdir(a.out):
        if old.endswith(".conf") and old not in files:
            os.remove(os.path.join(a.out, old))
    for name, body in files.items():
        with open(os.path.join(a.out, name), "w") as f:
            f.write(body)
    print("wrote %d files to %s" % (len(files), a.out))


if __name__ == "__main__":
    sys.exit(main())
